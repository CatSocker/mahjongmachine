def calculate_combined_reward(f_rank, s_change, r_improve, scores, params):
    """
    输入参数：
    - f_rank: 整场半庄结束后的最终顺位 (1-4)
    - s_change: 这一局（当前帧所属的小局）玩家点数的变化量（如和牌+3900，点炮-5200）
    - r_improve: 这一局内，玩家顺位的即时变动（如：从第3名升到第2名，则为 +1）
    - scores: 当前四家点数列表 [第一名分, 第二名分, 第三名分, 第四名分]
    - params: 外部传入的超参数字典
    """
    
    # 1. 【终局权重】映射：根据你设定的 (90, 45, 0, -135) 
    # 目标：让 AI 产生强烈的“避四”本能，因为第四名的惩罚(-135)远大于第一名的奖励(90)
    rank_map = {1: 90.0, 2: 45.0, 3: 0.0, 4: -135.0}
    R_final = rank_map[f_rank]
    
    # 2. 【即时顺位奖励】：
    # 目标：给 AI 提供更频繁的正反馈。即使还没打完半庄，只要这局顺位上升了就给奖励。
    # params['gamma_improve'] 通常设为 20 左右。
    R_improve = r_improve * params['gamma_improve']
    
    # 3. 【动态点数商值策略】：
    # 这是最核心的逻辑：点数的价值取决于你离“超车”或“被超”还有多远。
    s1, s2, s3, s4 = scores
    sigma = params['sigma_smooth']  # 平滑因子（建议10），防止分差极小时权重趋于无穷大
    
    # 根据当前顺位寻找“参照对手”分差 (dist)
    if f_rank == 1:
        # 如果我是第一名：
        # 赢点时（s_change > 0）：分母设为大常数（8000），让第一名赢小牌的欲望变低（没必要冒险）。
        # 输点时：参考我领先第二名（s1-s2）多少，领先越少，惩罚越重。
        dist = 80.0 if s_change > 0 else (s1 - s2)
    elif f_rank == 2:
        # 如果我是第二名：
        # 赢点：参考离第一名（s1-s2）多远。分差越小，权重越大（临门一脚最关键）。
        # 输点：参考离第三名（s2-s3）多远。分差越小，越怕被超，惩罚越重。
        dist = (s1 - s2) if s_change > 0 else (s2 - s3)
    elif f_rank == 3:
        # 如果我是第三名：
        # 参照逻辑同上：赢点看二位，输点看四位。
        dist = (s2 - s3) if s_change > 0 else (s3 - s4)
    else: # f_rank == 4
        # 如果我是第四名：
        # 赢点：参考离第三名（s3-s4）多远。
        # 输点：分母固定。防止分差太大时 AI 彻底“摆烂”。
        dist = (s3 - s4) if s_change > 0 else 120.0
    
    # 【商值计算】：收益 / (分差 + 平滑因子)
    # 意义：分差越小，分母越小，最终 R_score 越大。
    # 这迫使 AI 在“关键局（生死战）”中学习效率提升数倍。
    R_score = s_change / (abs(dist) + sigma)
    
    # 4. 【多维权重合成】：
    # alpha 和 beta 是调节系数。由于 R_score 算出来数值较小，通常给它乘个 100 对齐量级。
    total_w = (params['alpha'] * R_final) + R_improve + (params['beta'] * R_score * 100)
    
    # 5. 【梯度截断 (Clip)】：防止梯度爆炸的关键步骤。
    # 无论算出来的奖惩多夸张，强制限制在 [-300, 250] 之间，防止一个极端的点炮数据把模型参数跑飞。
    return max(min(total_w, params['clip_max']), params['clip_min'])

